// app/appointment.tsx
import { useState, useEffect } from "react";
import { StyleSheet, Text, View, ScrollView, Pressable, LayoutAnimation, Platform, UIManager } from "react-native";
import { useRouter } from "expo-router";
import { Screen } from "../components/Screen";
import { Button } from "../components/Button";
import { colors, radius, spacing } from "../constants/theme";
import { Ionicons } from "@expo/vector-icons";
import * as Haptics from "expo-haptics";

// Enable LayoutAnimation on Android
if (Platform.OS === "android" && UIManager.setLayoutAnimationEnabledExperimental) {
  UIManager.setLayoutAnimationEnabledExperimental(true);
}

export default function AppointmentScreen() {
  const router = useRouter();
  const [appointmentTime] = useState(() => {
    const d = new Date();
    d.setDate(d.getDate() + 1);
    d.setHours(10, 0, 0, 0);
    return d;
  });
  const [timeLeft, setTimeLeft] = useState(appointmentTime.getTime() - Date.now());
  const [isCarePlanExpanded, setIsCarePlanExpanded] = useState(false);

  useEffect(() => {
    const interval = setInterval(() => {
      const remaining = appointmentTime.getTime() - Date.now();
      setTimeLeft(remaining > 0 ? remaining : 0);
    }, 1000);
    return () => clearInterval(interval);
  }, [appointmentTime]);

  const formatTime = (ms: number) => {
    const totalSeconds = Math.floor(ms / 1000);
    const h = Math.floor(totalSeconds / 3600);
    const m = Math.floor((totalSeconds % 3600) / 60);
    const s = totalSeconds % 60;
    return `${h.toString().padStart(2, '0')}:${m.toString().padStart(2, '0')}:${s.toString().padStart(2, '0')}`;
  };

  const toggleCarePlan = () => {
    Haptics.impactAsync(Haptics.ImpactFeedbackStyle.Light);
    LayoutAnimation.configureNext(LayoutAnimation.Presets.easeInEaseOut);
    setIsCarePlanExpanded(!isCarePlanExpanded);
  };

  // In a real app, this would be generated by the AI based on the symptom
  const carePlan = [
    { title: "Dietary Restrictions", desc: "Avoid very cold or hot foods until evaluated.", icon: "restaurant-outline" },
    { title: "Pain Management", desc: "Use desensitizing toothpaste and avoid hard chewing.", icon: "medical-outline" },
    { title: "Oral Hygiene", desc: "Rinse gently with warm salt water twice a day.", icon: "water-outline" },
  ];

  return (
    <Screen>
      <ScrollView contentContainerStyle={styles.scroll}>
        
        <View style={styles.successHeader}>
          <View style={styles.checkCircle}>
            <Ionicons name="checkmark" size={40} color="#FFF" />
          </View>
          <Text style={styles.title}>Booked Successfully</Text>
          <Text style={styles.subtitle}>Bright Smile Dental</Text>
        </View>

        <View style={styles.ticket}>
          <View style={styles.ticketTop}>
            <Text style={styles.timerLabel}>TIME UNTIL APPOINTMENT</Text>
            <Text style={styles.timerValue}>{formatTime(timeLeft)}</Text>
            <View style={styles.reminderBadge}>
              <Ionicons name="notifications" size={14} color="#166534" />
              <Text style={styles.reminderText}>Reminder scheduled</Text>
            </View>
          </View>
          <View style={styles.divider} />
          <View style={styles.ticketBottom}>
            <View style={styles.detailRow}>
              <Ionicons name="calendar-outline" size={18} color={colors.textMuted} />
              <Text style={styles.detailText}>Tomorrow, 10:00 AM</Text>
            </View>
            <View style={styles.detailRow}>
              <Ionicons name="location-outline" size={18} color={colors.textMuted} />
              <Text style={styles.detailText}>123 Dental Ave, City</Text>
            </View>
          </View>
        </View>

        {/* NEW FEATURE: AI CARE PLAN ACCORDION */}
        <Pressable style={styles.accordionHeader} onPress={toggleCarePlan}>
          <View style={styles.accordionTitleRow}>
            <View style={styles.sparkleIcon}>
              <Ionicons name="sparkles" size={16} color="#FFF" />
            </View>
            <Text style={styles.accordionTitle}>Your Pre-Visit Care Plan</Text>
          </View>
          <Ionicons name={isCarePlanExpanded ? "chevron-up" : "chevron-down"} size={20} color={colors.textMuted} />
        </Pressable>

        {isCarePlanExpanded && (
          <View style={styles.carePlanContent}>
            <Text style={styles.carePlanSubtitle}>Generated by AI based on your symptoms.</Text>
            {carePlan.map((item, index) => (
              <View key={index} style={styles.careItem}>
                <View style={styles.careIconBox}>
                  <Ionicons name={item.icon as any} size={18} color={colors.accent} />
                </View>
                <View style={styles.careTextContainer}>
                  <Text style={styles.careItemTitle}>{item.title}</Text>
                  <Text style={styles.careItemDesc}>{item.desc}</Text>
                </View>
              </View>
            ))}
          </View>
        )}

      </ScrollView>

      <View style={styles.footer}>
        <Button title="View Audit Log" onPress={() => router.push("/audit")} />
        <Button title="Book another" variant="ghost" onPress={() => router.replace("/")} style={{ marginTop: spacing.sm }} />
      </View>
    </Screen>
  );
}

