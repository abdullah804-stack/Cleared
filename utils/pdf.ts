// utils/pdf.ts
import * as Print from "expo-print";
import * as Sharing from "expo-sharing";
import { Alert } from "react-native";

export async function generateClinicalPDF(userEmail: string, symptoms: string, planTrace: string[]) {
  const htmlContent = `
    <html>
      <head>
        <style>
          body { font-family: 'Helvetica Neue', Helvetica, Arial, sans-serif; padding: 40px; color: #111827; }
          .header { border-bottom: 2px solid #2563EB; padding-bottom: 20px; margin-bottom: 30px; }
          .logo { font-size: 24px; font-weight: 800; color: #2563EB; letter-spacing: -1px; }
          .subtitle { color: #6B7280; font-size: 14px; margin-top: 5px; }
          .section { margin-bottom: 30px; }
          .section-title { font-size: 16px; font-weight: 700; color: #2563EB; text-transform: uppercase; letter-spacing: 1px; margin-bottom: 10px; }
          .content-box { background: #F9FAFB; padding: 20px; border-radius: 8px; border: 1px solid #E5E7EB; }
          .trace-item { margin-bottom: 10px; font-family: monospace; font-size: 12px; color: #4B5563; }
          .footer { margin-top: 50px; font-size: 10px; color: #9CA3AF; text-align: center; }
        </style>
      </head>
      <body>
        <div class="header">
          <div class="logo">Cleared AI</div>
          <div class="subtitle">Pre-Visit Clinical Summary</div>
        </div>

        <div class="section">
          <div class="section-title">Patient Information</div>
          <div class="content-box">
            <p><strong>Email:</strong> ${userEmail}</p>
            <p><strong>Date:</strong> ${new Date().toLocaleDateString()}</p>
          </div>
        </div>

        <div class="section">
          <div class="section-title">Reported Symptoms</div>
          <div class="content-box">
            <p>"${symptoms}"</p>
          </div>
        </div>

        <div class="section">
          <div class="section-title">AI Action Trace</div>
          <div class="content-box">
            ${planTrace.map(step => `<div class="trace-item">• ${step}</div>`).join("")}
          </div>
        </div>

        <div class="footer">
          Generated by Cleared App. This is an AI-assisted summary and not a medical diagnosis.
        </div>
      </body>
    </html>
  `;

  try {
    const { uri } = await Print.printToFileAsync({ html: htmlContent });
    await Sharing.shareAsync(uri, { UTI: '.pdf', mimeType: 'application/pdf' });
  } catch (error) {
    Alert.alert("Error", "Could not generate PDF.");
  }
}